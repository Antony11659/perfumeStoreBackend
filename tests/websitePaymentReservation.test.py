class PaymentReservationTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        for tool in ("initdb", "pg_ctl", "psql"):
            if shutil.which(tool) is None:
                raise RuntimeError(f"Local PostgreSQL tool required: {tool}")
        directory = tempfile.TemporaryDirectory(prefix="ldp-pg-", dir="/tmp")
        cls.addClassCleanup(directory.cleanup)
        cls.cluster = Path(directory.name) / "data"
        cls.run_tool("initdb", "-D", cls.cluster, "-U", "fixture_admin",
                     "--auth=trust", "--no-locale", "--encoding=UTF8")
        cls.run_tool("pg_ctl", "-D", cls.cluster, "-l", Path(directory.name) / "postgres.log",
                     "-o", f"-c listen_addresses='' -k {directory.name}", "-w", "start")
        cls.addClassCleanup(cls.run_tool, "pg_ctl", "-D", cls.cluster, "-m", "immediate", "-w", "stop")
        cls.psql = [
            shutil.which("psql"), "-XAtq", "-v", "ON_ERROR_STOP=1",
            "-h", directory.name, "-p", "5432", "-U", "fixture_admin", "-d", "postgres",
        ]
        if cls.query("SHOW listen_addresses") != "":
            raise RuntimeError("Disposable cluster must have TCP disabled")
        cls.query(FIXTURE)
        cls.run_tool(*cls.psql, "-f", STAGE_2)
        cls.run_tool(*cls.psql, "-f", PAYMENT)

    @staticmethod
    def run_tool(tool, *args):
        # Explicit local arguments and an empty child environment exclude
        # inherited PG connection settings, credentials and service files.
        result = subprocess.run([shutil.which(tool) or tool, *args], env={},
                                capture_output=True, text=True, timeout=30, check=False)
        if result.returncode:
            raise RuntimeError(f"{Path(tool).name}: {result.stderr.strip()} {result.stdout.strip()}")
        return result.stdout.strip()

    @classmethod
    def query(cls, sql):
        return cls.run_tool(*cls.psql, "-c", sql)

    def seed(self, number, status="new"):
        return int(self.query(
            "INSERT INTO public.website_orders (order_number, total, status) "
            f"VALUES ('{number}', 1250.45, '{status}') RETURNING id"
        ))

    @staticmethod
    def claim_sql(order_id):
        return f"SELECT * FROM public.reserve_website_order_payment_v1({order_id});"

    def claim(self, order_id):
        return self.query("SET ROLE service_role; " + self.claim_sql(order_id))

    def state(self, order_id):
        return self.query(
            f"SELECT coalesce(payment_state, 'unset') FROM public.website_orders WHERE id = {order_id}"
        )

    def test_a_normal_reservation(self):
        order_id = self.seed("normal")
        self.assertEqual(self.claim(order_id), f"{order_id}|normal|1250.45|reserved")
        self.assertEqual(self.state(order_id), "reserved")

    def test_b_concurrent_reservation(self):
        order_id = self.seed("concurrent")
        self.assert_one_concurrent_winner(
            self.claim_sql(order_id), f"{order_id}|concurrent|1250.45|reserved"
        )
        self.assertEqual(self.state(order_id), "reserved")

    def assert_one_concurrent_winner(self, sql, expected):
        # Keep A's row lock until PostgreSQL reports B waiting on it. Both
        # psql processes have independent backend sessions.
        with subprocess.Popen(self.psql, env={}, text=True, stdin=subprocess.PIPE,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE) as first:
            try:
                first.stdin.write("BEGIN; SET LOCAL statement_timeout = '8s'; "
                                  "SET ROLE service_role; " + sql + "\n")
                first.stdin.flush()
                self.assertEqual(first.stdout.readline().strip(), expected)
                contender_sql = ("/* payment_transition_contender */ "
                                 "SET statement_timeout = '8s'; SET ROLE service_role; " + sql)
                with subprocess.Popen([*self.psql, "-c", contender_sql], env={}, text=True,
                                      stdout=subprocess.PIPE, stderr=subprocess.PIPE) as second:
                    try:
                        deadline = time.monotonic() + 5
                        while time.monotonic() < deadline:
                            if self.query(
                                "SELECT count(*) FROM pg_stat_activity "
                                "WHERE query LIKE '/* payment_transition_contender */%' "
                                "AND wait_event_type = 'Lock'"
                            ) == "1":
                                break
                            self.assertIsNone(second.poll(), "Contender exited before waiting on the update")
                            time.sleep(0.02)
                        else:
                            self.fail("PostgreSQL never reported the contender waiting on a row lock")
                        first.communicate("COMMIT;\n", timeout=5)
                        self.assertEqual(first.returncode, 0)
                        output, errors = second.communicate(timeout=5)
                        self.assertEqual(second.returncode, 0, errors)
                        self.assertEqual(output.strip(), "")
                    finally:
                        if second.poll() is None:
                            second.kill()
            finally:
                if first.poll() is None:
                    first.kill()
    def test_c_sequential_retry(self):
        order_id = self.seed("sequential")
        self.assertEqual(self.claim(order_id), f"{order_id}|sequential|1250.45|reserved")
        self.assertEqual(self.claim(order_id), "")
        self.assertEqual(self.state(order_id), "reserved")

    def test_d_claim_survives_connection_close(self):
        order_id = self.seed("disconnect")
        result = self.run_tool(*self.psql, "-c", "BEGIN", "-c", "SET ROLE service_role",
                               "-c", self.claim_sql(order_id), "-c", "COMMIT")
        # The commit and process exit both complete before the next session.
        self.assertEqual(result, f"{order_id}|disconnect|1250.45|reserved")
        self.assertEqual(self.claim(order_id), "")
        self.assertEqual(self.state(order_id), "reserved")

    def test_e_paid_order(self):
        order_id = self.seed("paid", "paid")
        self.assertEqual(self.claim(order_id), "")
        self.assertEqual(self.state(order_id), "unset")

    def test_f_unknown_order(self):
        snapshot = "SELECT jsonb_agg(to_jsonb(o) ORDER BY id) FROM public.website_orders o"
        before = self.query(snapshot)
        self.assertEqual(self.claim(-1), "")
        self.assertEqual(self.query(snapshot), before)

    def test_g_stage_2_compatibility(self):
        self.assertEqual(self.query(
            "SELECT ROW(payment_state, ozon_payment_id, payment_link) IS NULL "
            "FROM public.website_orders WHERE order_number = 'pre-migration'"
        ), "t")
        key = "'00000000-0000-4000-8000-000000000001'"
        request_hash = "'" + "a" * 64 + "'"
        rpc = f"SELECT public.persist_website_order_v1({key}, {request_hash}"
        as_backend = "SET ROLE service_role; "
        self.assertEqual(json.loads(self.query(as_backend + rpc + ")")), {"outcome": "ready"})
        created = json.loads(self.query(as_backend + rpc + """, '{
          "order": {"order_number": "stage-2", "pricing_mode": "website",
                    "subtotal": 100, "delivery_price": 0, "total": 100},
          "items": [{"variant_id": 1, "quantity": 1, "unit_price": 100, "line_total": 100}],
          "delivery": {"provider": "ozon", "delivery_type": "pvz"}
        }')"""))
        self.assertEqual(created["outcome"], "created")
        order = created["response"]["order"]
        self.assertEqual(order, {
            "id": order["id"], "orderNumber": "stage-2", "pricingMode": "website",
            "subtotal": 100, "deliveryPrice": 0, "total": 100, "status": "new",
        })
        self.assertEqual(self.query(
            "SELECT ROW(payment_state, ozon_payment_id, payment_link) IS NULL "
            f"FROM public.website_orders WHERE id = {int(order['id'])}"
        ), "t")
        replay = json.loads(self.query(as_backend + rpc + ")"))
        self.assertEqual(replay, {"outcome": "completed", "response": created["response"]})
        conflict = json.loads(self.query(
            as_backend + f"SELECT public.persist_website_order_v1({key}, repeat('b', 64))"
        ))
        self.assertEqual(conflict, {"outcome": "conflict"})
        for table in ("website_order_items", "website_order_deliveries"):
            self.assertEqual(self.query(
                f"SELECT count(*) FROM public.{table} WHERE order_id = {int(order['id'])}"
            ), "1")



    def seed_payment(self, number, provider_id="settlement-provider", total="1250.45",
                     status="new", state="ready"):
        provider = f"'{provider_id}'" if state == "ready" else "NULL"
        link = "'https://payment.example.invalid/link'" if state == "ready" else "NULL"
        payment_state = f"'{state}'" if state is not None else "NULL"
        return int(self.query(
            "INSERT INTO public.website_orders "
            "(order_number, total, status, payment_state, ozon_payment_id, payment_link, updated_at) "
            f"VALUES ('{number}', {total}, '{status}', {payment_state}, {provider}, {link}, "
            "'2000-01-01 UTC') RETURNING id"
        ))

    @staticmethod
    def confirm_sql(order_id, number, provider_id="settlement-provider", amount=125045):
        return ("SELECT * FROM public.confirm_website_order_payment_v1("
                f"{order_id}, '{provider_id}', '{number}', {amount});")

    def payment_row(self, order_id):
        return json.loads(self.query(
            f"SELECT to_jsonb(o) FROM public.website_orders o WHERE id = {order_id}"
        ))

    def test_settlement_first_transition_and_replay(self):
        order_id = self.seed_payment("settle-first", "provider-first")
        before = self.payment_row(order_id)
        sql = "SET ROLE service_role; " + self.confirm_sql(order_id, "settle-first", "provider-first")
        self.assertEqual(self.query(sql), f"{order_id}|settle-first|1250.45|paid|confirmed|provider-first")
        after = self.payment_row(order_id)
        self.assertGreater(after["updated_at"], before["updated_at"])
        self.assertEqual(after, {
            **before, "status": "paid", "payment_state": "confirmed",
            "updated_at": after["updated_at"],
        })
        self.assertEqual(self.query(sql), "")
        self.assertEqual(self.payment_row(order_id), after)

    def test_settlement_concurrent_confirmations(self):
        order_id = self.seed_payment("settle-race", "provider-race")
        self.assert_one_concurrent_winner(
            self.confirm_sql(order_id, "settle-race", "provider-race"),
            f"{order_id}|settle-race|1250.45|paid|confirmed|provider-race",
        )
        row = self.payment_row(order_id)
        self.assertEqual((row["status"], row["payment_state"]), ("paid", "confirmed"))

    def test_settlement_mismatches_and_ineligible_orders(self):
        self.seed_payment("different-order", "provider-other")
        cases = [
            ("wrong-provider", {}, {"provider_id": "not-saved"}),
            ("wrong-reference", {}, {"number": "different-order"}),
            ("wrong-amount", {}, {"amount": 125046}),
            ("fractional-kopecks", {"total": "1250.451"}, {}),
            ("zero-amount", {}, {"amount": 0}),
            ("negative-amount", {}, {"amount": -1}),
            ("zero-total", {"total": "0"}, {"amount": 0}),
            ("negative-total", {"total": "-1"}, {"amount": -100}),
            ("reserved", {"state": "reserved"}, {}),
            ("unknown", {"state": "unknown"}, {}),
            ("already-paid", {"status": "paid"}, {}),
            ("cancelled", {"status": "cancelled"}, {}),
            ("unrelated-provider", {}, {"provider_id": "provider-other"}),
            ("unsaved", {"state": None}, {}),
            ("blank-provider", {}, {"provider_id": " "}),
            ("blank-reference", {}, {"number": ""}),
        ]
        for label, order_fields, request_fields in cases:
            with self.subTest(case=label):
                provider = f"provider-{label}"
                order_id = self.seed_payment(label, provider, **order_fields)
                before = self.payment_row(order_id)
                request = {"number": label, "provider_id": provider, **request_fields}
                self.assertEqual(self.query(
                    "SET ROLE service_role; " + self.confirm_sql(order_id, **request)
                ), "")
                self.assertEqual(self.payment_row(order_id), before)

    def test_settlement_lost_response_after_commit(self):
        order_id = self.seed_payment("settle-lost-response", "provider-lost-response")
        sql = self.confirm_sql(order_id, "settle-lost-response", "provider-lost-response")
        # Commit on a separate connection and discard the RPC result at the client boundary.
        subprocess.run([*self.psql, "-c", "BEGIN", "-c", "SET ROLE service_role",
                        "-c", sql, "-c", "COMMIT"], env={}, check=True, timeout=10,
                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        self.assertEqual(self.query("SET ROLE service_role; " + sql), "")
        row = self.payment_row(order_id)
        self.assertEqual(
            (row["status"], row["payment_state"], row["order_number"], row["ozon_payment_id"]),
            ("paid", "confirmed", "settle-lost-response", "provider-lost-response"),
        )

    def test_settlement_permissions(self):
        order_id = self.seed_payment("settle-grants", "provider-grants")
        sql = self.confirm_sql(order_id, "settle-grants", "provider-grants")
        for role in ("anon", "authenticated"):
            with self.subTest(role=role):
                with self.assertRaisesRegex(RuntimeError, "permission denied for function"):
                    self.query(f"SET ROLE {role}; " + sql)
        self.assertEqual(self.query("SET ROLE service_role; " + sql),
                         f"{order_id}|settle-grants|1250.45|paid|confirmed|provider-grants")

if __name__ == "__main__":
    unittest.main(verbosity=2)

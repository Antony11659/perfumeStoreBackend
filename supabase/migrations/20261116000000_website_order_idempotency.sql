BEGIN;

-- Backend-only idempotency for both /orders and /website/orders.
-- Reserve with p_prepared = NULL in a separate committed RPC before validation.
-- A reservation binds the key/hash; it does not grant exclusive worker ownership.
-- Concurrent workers may validate, but only one can finalize the order.
CREATE TABLE public.website_order_requests (
  idempotency_key uuid PRIMARY KEY,
  request_hash text NOT NULL
    CHECK (request_hash ~ '^[0-9a-f]{64}$'),
  hash_version smallint NOT NULL DEFAULT 1
    CHECK (hash_version = 1),
  state text NOT NULL DEFAULT 'reserved'
    CHECK (state IN ('reserved', 'completed')),
  -- Completed orders cannot be deleted, even by an upstream cascading delete.
  -- Existing child ON DELETE CASCADE foreign keys are unchanged. Any retention
  -- workflow deleting completed orders needs a separately reviewed policy that
  -- preserves key history; deleting request records would allow duplicate orders.
  order_id bigint UNIQUE
    REFERENCES public.website_orders(id) ON DELETE RESTRICT,
  response_body jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT website_order_requests_state_consistency CHECK (
    (
      state = 'reserved'
      AND order_id IS NULL
      AND response_body IS NULL
      AND completed_at IS NULL
    )
    OR
    (
      state = 'completed'
      AND order_id IS NOT NULL
      AND response_body IS NOT NULL
      AND jsonb_typeof(response_body) = 'object'
      AND completed_at IS NOT NULL
    )
  )
);

ALTER TABLE public.website_order_requests ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.website_order_requests
  FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE ON TABLE public.website_order_requests
  TO service_role;

-- CREATE FUNCTION deliberately fails rather than replacing an existing function.
-- p_prepared is constructed ONLY by the trusted backend after catalog, pricing,
-- promo and Ozon validation. Never expose this RPC/input to frontend clients or
-- forward client prices. This function persists a trusted snapshot; it does not
-- calculate prices, create shipments or create payments.
--
-- Expected prepared shape: {"order": {...}, "items": [{...}], "delivery": {...}}
-- using the existing service's database column names. IDs/default timestamps
-- are generated by the existing tables; caller-supplied IDs are never inserted.
CREATE FUNCTION public.persist_website_order_v1(
  p_key uuid,
  p_hash text,
  p_prepared jsonb DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
SET lock_timeout = '2s'
AS $$
DECLARE
  r public.website_order_requests%ROWTYPE;
  o public.website_orders%ROWTYPE;
  d public.website_order_deliveries%ROWTYPE;
  saved public.website_orders%ROWTYPE;
  result jsonb;
BEGIN
  IF p_key IS NULL OR p_hash IS NULL
     OR p_hash !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'Invalid idempotency arguments'
      USING ERRCODE = '22023';
  END IF;

  SELECT * INTO r
  FROM public.website_order_requests
  WHERE idempotency_key = p_key;

  IF NOT FOUND THEN
    -- The primary key resolves concurrent first reservations. Under the default
    -- READ COMMITTED isolation, the next statement sees the winning reservation.
    -- Contention may raise a lock timeout: retry the same key/hash, never a new key.
    INSERT INTO public.website_order_requests (
      idempotency_key, request_hash
    )
    VALUES (p_key, p_hash)
    ON CONFLICT (idempotency_key) DO NOTHING;

    SELECT * INTO STRICT r
    FROM public.website_order_requests
    WHERE idempotency_key = p_key;
  END IF;

  IF r.request_hash <> p_hash THEN
    RETURN jsonb_build_object('outcome', 'conflict');
  END IF;

  IF r.state = 'completed' THEN
    RETURN jsonb_build_object(
      'outcome', 'completed',
      'response', r.response_body
    );
  END IF;

  IF p_prepared IS NULL THEN
    RETURN jsonb_build_object('outcome', 'ready');
  END IF;

  BEGIN
    SELECT * INTO STRICT r
    FROM public.website_order_requests
    WHERE idempotency_key = p_key
    FOR UPDATE NOWAIT;
  EXCEPTION
    WHEN lock_not_available THEN
      RETURN jsonb_build_object('outcome', 'in_progress');
  END;

  -- Another finalizer may have committed between the first read and this lock.
  IF r.request_hash <> p_hash THEN
    RETURN jsonb_build_object('outcome', 'conflict');
  END IF;

  IF r.state = 'completed' THEN
    RETURN jsonb_build_object(
      'outcome', 'completed',
      'response', r.response_body
    );
  END IF;

  IF jsonb_typeof(p_prepared->'order') IS DISTINCT FROM 'object'
     OR jsonb_typeof(p_prepared->'delivery') IS DISTINCT FROM 'object'
     OR jsonb_typeof(p_prepared->'items') IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Invalid prepared order'
      USING ERRCODE = '22023';
  END IF;

  IF jsonb_array_length(p_prepared->'items') = 0 THEN
    RAISE EXCEPTION 'Order items required'
      USING ERRCODE = '22023';
  END IF;

  -- Use actual table composite types rather than assuming monetary, PVZ or
  -- cutoff column types. Explicit INSERT columns preserve identity/defaults.
  o := jsonb_populate_record(
    NULL::public.website_orders,
    p_prepared->'order'
  );
  d := jsonb_populate_record(
    NULL::public.website_order_deliveries,
    p_prepared->'delivery'
  );

  INSERT INTO public.website_orders (
    order_number, customer_name, phone, messenger, city,
    address, comment, promo_code, pricing_mode,
    subtotal, delivery_price, total, status
  )
  VALUES (
    o.order_number, o.customer_name, o.phone, o.messenger, o.city,
    o.address, o.comment, o.promo_code, o.pricing_mode,
    o.subtotal, o.delivery_price, o.total, 'new'
  )
  RETURNING * INTO saved;

  INSERT INTO public.website_order_items (
    order_id, variant_id, quantity, unit_price, line_total
  )
  SELECT
    saved.id, i.variant_id, i.quantity, i.unit_price, i.line_total
  FROM jsonb_populate_recordset(
    NULL::public.website_order_items,
    p_prepared->'items'
  ) AS i;

  INSERT INTO public.website_order_deliveries (
    order_id, provider, delivery_type, delivery_point_id,
    delivery_point_name, delivery_point_address,
    estimated_delivery_days, delivery_cost, insurance_cost,
    customer_delivery_price, cutoff_at,
    external_order_number, external_posting_number, status
  )
  VALUES (
    saved.id, d.provider, d.delivery_type, d.delivery_point_id,
    d.delivery_point_name, d.delivery_point_address,
    d.estimated_delivery_days, d.delivery_cost, d.insurance_cost,
    d.customer_delivery_price, d.cutoff_at,
    NULL, NULL, 'calculated'
  );

  result := jsonb_build_object(
    'success', true,
    'order', jsonb_build_object(
      'id', saved.id,
      'orderNumber', saved.order_number,
      'pricingMode', saved.pricing_mode,
      'subtotal', saved.subtotal,
      'deliveryPrice', saved.delivery_price,
      'total', saved.total,
      'status', saved.status
    )
  );

  UPDATE public.website_order_requests
  SET state = 'completed',
      order_id = saved.id,
      response_body = result,
      completed_at = now()
  WHERE idempotency_key = p_key;

  RETURN jsonb_build_object(
    'outcome', 'created',
    'response', result
  );
  -- Do not catch persistence errors: all order writes and completion must roll
  -- back together. A reservation from an earlier committed RPC remains usable.
  -- Identity sequences may have gaps after rollback; that is expected.
  -- A lost/timeout response does NOT prove rollback: resolve using the same key.
END;
$$;

REVOKE ALL ON FUNCTION public.persist_website_order_v1(uuid, text, jsonb)
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.persist_website_order_v1(uuid, text, jsonb)
  TO service_role;

COMMIT;
